def svg(im):
 parts=[]
 for y in range(im.height):
  x=0
  while x<im.width:
   c=im.getpixel((x,y));start=x
   while x<im.width and im.getpixel((x,y))==c:x+=1
   if c[3]:parts.append(f'<rect x="{start}" y="{y}" width="{x-start}" height="1" fill="#{c[0]:02x}{c[1]:02x}{c[2]:02x}"/>')
 return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {im.width} {im.height}" shape-rendering="crispEdges">'+''.join(parts)+'</svg>\n'
